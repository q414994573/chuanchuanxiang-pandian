const {test}=require('node:test'),assert=require('node:assert/strict'),fs=require('fs'),path=require('path');
const root=path.join(__dirname,'..');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
test('redesign preview stays off the production pages and only writes test orders',()=>{
 const index=read('index.html');
 assert.equal(index.includes('redesign-preview'),false);
 assert.equal(index.includes('新版预览'),false);
 const cloudTest=read('cloud-test/index.html');
 assert.match(cloudTest,/云端测试版·不是正式订单/);
 assert.match(cloudTest,/CCX_CLOUD_TEST=true/);
 const page=read('redesign-preview/index.html');
 assert.match(page,/新版预览·不是正式订单/);
 assert.match(page,/preview\.bundle\.js/);
 assert.doesNotMatch(page,/CCX_CLOUD_TEST/);
 const js=read('redesign-preview/preview.js');
 const css=read('redesign-preview/preview.css');
 const bundle=read('redesign-preview/preview.bundle.js');
 assert.match(js,/cloudOrderId\(draft\.id,true\)/);
 assert.match(js,/assertCloudOrderId\(id,true\)/);
 assert.match(js,/ccx-redesign-session:/);
 assert.equal(js.includes('ccx-count-session:'),false);
 assert.equal(js.includes('ccx-cloud-test-session:'),false);
 assert.match(js,/startsWith\('test-'\)/);
 assert.match(js,/样例只在这台手机上改了看，没有写入云端/);
 assert.match(bundle,/ccx-redesign-session:/);
 assert.equal(bundle.includes('ccx-count-session:'),false);
 const blob=page+js+css;
 assert.equal(blob.includes('最低备货'),false);
 assert.equal(blob.includes('重点商品'),false);
 assert.equal(blob.includes('星标'),false);
 const cfg=JSON.parse(read('redesign-preview/firebase-config.json'));
 assert.equal(cfg.enabled,true);
 assert.equal(cfg.firebase.projectId,'chuanchuanxiang-order');
 const products=JSON.parse(read('current-order.json')).products;
 assert.equal(products.length,129);
 assert.equal(products.filter(p=>p.cat==='kr').length,45);
 assert.equal(products.filter(p=>p.cat==='cn').length,66);
 assert.equal(products.filter(p=>p.cat==='other').length,18);
});
