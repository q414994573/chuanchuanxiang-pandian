const {test}=require('node:test'),assert=require('node:assert/strict'),fs=require('fs'),path=require('path');
const root=path.join(__dirname,'..');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
test('redesign preview stays off the production pages and only writes test orders',()=>{
 const index=read('index.html');
 assert.equal(index.includes('redesign-preview'),false);
 assert.equal(index.includes('新版预览'),false);
 const cloudTest=read('cloud-test/index.html');
 assert.match(cloudTest,/云端测试版·不是正式订单/);
 assert.match(cloudTest,/CCX_CLOUD_TEST=true/);
 const page=read('redesign-preview/index.html');
 assert.match(page,/新版预览·不是正式订单/);
 assert.match(page,/preview\.bundle\.js/);
 assert.doesNotMatch(page,/CCX_CLOUD_TEST/);
 const js=read('redesign-preview/preview.js');
 const css=read('redesign-preview/preview.css');
 const bundle=read('redesign-preview/preview.bundle.js');
 assert.match(js,/cloudOrderId\(draft\.id,true\)/);
 assert.match(js,/assertCloudOrderId\(id,true\)/);
 assert.match(js,/ccx-redesign-draft-v2/);
 assert.match(js,/countDrafts/);
 assert.equal(js.includes('ccx-count-session:'),false);
 assert.equal(js.includes('ccx-cloud-test-session:'),false);
 assert.match(js,/startsWith\('test-'\)/);
 assert.match(js,/样例不会写入云端/);
 assert.match(page,/manifest\.webmanifest/);
 assert.match(read('redesign-preview/manifest.webmanifest'),/천천향 盘货/);
 assert.equal(index.includes('manifest.webmanifest'),false);
 assert.match(bundle,/ccx-redesign-draft-v2/);
 assert.equal(bundle.includes('ccx-count-session:'),false);
 const blob=page+js+css;
 assert.equal(blob.includes('最低备货'),false);
 assert.equal(blob.includes('重点商品'),false);
 assert.equal(blob.includes('星标'),false);
 const cfg=JSON.parse(read('redesign-preview/firebase-config.json'));
 assert.equal(cfg.enabled,true);
 assert.equal(cfg.firebase.projectId,'chuanchuanxiang-order');
 const products=JSON.parse(read('current-order.json')).products;
 assert.equal(products.length,129);
 assert.equal(products.filter(p=>p.cat==='kr').length,45);
 assert.equal(products.filter(p=>p.cat==='cn').length,66);
 assert.equal(products.filter(p=>p.cat==='other').length,18);
 assert.match(js,/Flow\.stripe\(n-1\)/);
 assert.match(js,/Flow\.stripe\(i\)/);
 assert.match(css,/--band:#d4ccc4/);
 assert.match(css,/\.line\.band\{background:var\(--band\)\}/);
 assert.match(css,/\.line\.on\{background:#f4b8c0\}/);
 assert.match(css,/\.order\.yellow\{background:#ffe14a\}/);
 assert.match(css,/\.order\.dead\{background:#b7b0a9\}/);
 assert.match(css,/\.order\.on\{background:#f4b8c0\}/);
 assert.match(css,/\.warnrow\.band\{background:#ffd09a\}/);
 assert.ok(css.indexOf('.line.band')<css.indexOf('.line.on'));
 assert.ok(css.indexOf('.order.band')<css.indexOf('.order.yellow'));
 assert.ok(css.indexOf('.order.yellow')<css.indexOf('.order.dead'));
 assert.ok(css.indexOf('.order.dead')<css.indexOf('.order.on'));
 assert.match(js,/return stockShown\(p\);/);
 assert.match(js,/quantity\|\|''/);
 assert.equal(js.includes("'空':v"),false);
 assert.equal(js.includes("'空':q"),false);
 assert.match(js,/aria-label=/);
 assert.match(css,/\.cell b\{[^}]*min-height:1\.15em/);
 assert.match(js,/data-act="close"/);
 assert.match(js,/>文字</);
 assert.match(js,/>123</);
 assert.match(js,/viewCat===cat/);
 assert.match(js,/p\.cat!==viewCat/);
 assert.match(js,/data-act="ordercat"/);
 assert.match(js,/\$\{n\}样/);
 assert.match(js,/mark red/);
 assert.match(js,/mark yellow/);
 assert.equal(js.includes('同上次'),false);
 assert.equal(js.includes('上次没订'),false);
 assert.match(bundle,/\\u6536\\u8D77/);
 assert.equal(bundle.includes('\\u540C\\u4E0A\\u6B21'),false);
 assert.equal(bundle.includes('\\u4E0A\\u6B21\\u6CA1\\u8BA2'),false);
 assert.equal(read('firestore.rules').includes('countDrafts'),true);
});
