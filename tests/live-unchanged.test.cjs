const {test}=require('node:test'),assert=require('node:assert/strict'),fs=require('fs'),path=require('path');
const root=path.join(__dirname,'..');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
test('production homepage enables cloud and stays separate from the test page',()=>{
 const index=read('index.html');
 assert.match(index,/cloud-app\.bundle\.js/);
 assert.match(index,/id="cloudRoot"/);
 assert.equal(index.includes('CCX_CLOUD_TEST'),false);
 assert.equal(index.includes('云端测试版'),false);
 assert.equal(index.includes('cloud-test'),false);
 const rootConfig=JSON.parse(read('firebase-config.json'));
 assert.equal(rootConfig.enabled,true);
 assert.equal(rootConfig.firebase.projectId,'chuanchuanxiang-order');
 assert.equal(rootConfig.firebase.authDomain,'chuanchuanxiang-order.firebaseapp.com');
 const page=read('cloud-test/index.html');
 assert.match(page,/云端测试版·不是正式订单/);
 assert.match(page,/CCX_CLOUD_TEST=true/);
 assert.match(page,/ccx-cloud-test-session:/);
 assert.doesNotMatch(page,/href="[^"]*index\.html"/);
 const config=JSON.parse(read('cloud-test/firebase-config.json'));
 assert.equal(config.enabled,true);
 assert.equal(config.firebase.projectId,'chuanchuanxiang-order');
 assert.equal(config.firebase.authDomain,'chuanchuanxiang-order.firebaseapp.com');
 const count=read('count-app.js');
 assert.match(count,/CCX_COUNT_STORAGE_PREFIX\|\|'ccx-count-session:'/);
 assert.match(count,/复制本分类订单/);
 assert.doesNotMatch(count,/复制这家订单/);
 assert.match(count,/仅云端测试页可以把其余商品标成本次不订/);
 const products=JSON.parse(read('current-order.json')).products;
 assert.equal(products.length,129);
 assert.equal(products.filter(p=>p.cat==='kr').length,45);
 assert.equal(products.filter(p=>p.cat==='cn').length,66);
 assert.equal(products.filter(p=>p.cat==='other').length,18);
 const backup=read('backups/index-before-firebase-20261020.html');
 assert.equal(backup.includes('cloud-app.bundle'),false);
 assert.equal(backup.includes('id="cloudRoot"'),false);
});
